import { test, expect } from './fixtures';
test.setTimeout(180000);
test('Pending, absent and failed metrics withhold proof; computed zero survives', { tag: '@critical' }, async ({ page }) => {
  let response: Record<string, unknown> = { strategy: 'Exact', provenance: 'Exact', rtp: 0, hitFrequency: 0, volatility: 0 };
  let status = 200;
  let releaseResponse: () => void = () => {};
  let responseGate = new Promise<void>(resolve => { releaseResponse = resolve; });
  await page.route('**/api/evaluate/light', async route => {
    await responseGate;
    await route.fulfill({ status, json: response });
  });
  await page.goto('/build', { waitUntil: 'domcontentloaded' });
  const metrics = page.getByLabel('Model evaluation');
  await expect(metrics).toContainText('Calculating');
  await expect(metrics.locator('.prov')).toHaveCount(0);
  releaseResponse();
  await expect(metrics).toContainText('0.00');
  await expect(metrics.locator('.prov.exact')).toHaveCount(3);
  response = { strategy: 'Exact', provenance: 'Exact' };
  responseGate = new Promise<void>(resolve => { releaseResponse = resolve; });
  await page.getByRole('button', { name: 'Load coin example' }).click();
  await expect(metrics).toContainText('Calculating');
  await expect(metrics.locator('.prov')).toHaveCount(0);
  releaseResponse();
  await expect(metrics).toContainText('Not evaluated');
  await expect(metrics).not.toContainText('0.00');
  status = 503;
  await page.getByRole('button', { name: 'Build Nine Lives graph' }).click();
  await expect(metrics).toContainText('Unavailable');
  await expect(metrics.locator('.prov')).toHaveCount(0);
  status = 200;
  response = { strategy: 'NeedsFullRun', rtp: 0 };
  await page.getByRole('button', { name: 'Load coin example' }).click();
  await expect(metrics).toContainText('Needs full run');
  const sink = page.locator('.react-flow__node[data-id="coin-sink"]');
  await expect(sink).toHaveCount(1);
  await expect(sink).toContainText('—');
  await expect(sink).not.toContainText('0.00%');
});
test('Missing interval bounds withhold proof and PAR exports keep absent fields unlabelled', { tag: '@critical' }, async ({ page }) => {
  let response = { strategy: 'Exact', provenance: 'ExactInterval', rtp: 0.9 } as Record<string, unknown>;
  await page.route('**/api/evaluate/light', route => route.fulfill({ json: response }));
  await page.goto('/build'); const metrics = page.getByLabel('Model evaluation'); await expect(metrics).toContainText('Not evaluated'); await expect(metrics.locator('.prov')).toHaveCount(0);
  response = { strategy: 'Exact', provenance: 'ExactInterval', rtp: 0.9, lo: 0.8, hi: 1, hitFrequency: 0.2 };
  await page.getByRole('button', { name: 'Load coin example' }).click(); await expect(metrics.locator('.prov')).toHaveCount(1); await expect(metrics).toContainText('RTP ratio bounds: 0.8 to 1');
  response = { strategy: 'Exact', provenance: 'Exact', rtp: 0.5 };
  await page.getByRole('tab', { name: 'Export', exact: true }).click(); const button = page.getByRole('button', { name: /printable summary/ }); await expect(button).toBeEnabled();
  const downloaded = page.waitForEvent('download'); await button.click(); const { readFile } = await import('node:fs/promises'); const html = await readFile((await (await downloaded).path())!, 'utf8');
  expect(html).toContain('Hit Frequency <span class="prov">Unavailable</span>'); expect(html).toContain('Volatility <span class="prov">Unavailable</span>');
});
